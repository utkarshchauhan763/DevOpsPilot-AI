
const OLLAMA_URL = "http://127.0.0.1:11434/api/generate";

const analyzeIncident = async ({
    title,
    description,
    service,
    severity,
    logs
}) => {
    try {
        const prompt = `
You are an experienced DevOps incident analysis assistant.

Analyze the following production incident.

Incident Details:
Title: ${title}
Description: ${description}
Service: ${service}
Severity: ${severity}

Error Logs:
${logs || "No logs provided."}

Return your analysis as valid JSON using exactly this structure:

{
    "rootCause": "Explain the most likely root cause",
    "impact": "Explain the possible impact on users and the application",
    "troubleshootingSteps": [
        "First troubleshooting step",
        "Second troubleshooting step",
        "Third troubleshooting step"
    ],
    "prevention": [
        "First prevention recommendation",
        "Second prevention recommendation"
    ]
}

Rules:
- Return JSON only.
- Do not include Markdown code fences.
- Keep recommendations technically accurate and actionable.
- Do not claim certainty when evidence is insufficient.
- If information is insufficient, clearly mention that.
`;

        const response = await fetch(OLLAMA_URL, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                model: "llama3.2:latest",
                prompt,
                stream: false,
                format: "json"
            })
        });

        if (!response.ok) {
            throw new Error(
                `Ollama API request failed: ${response.status}`
            );
        }

        const result = await response.json();

        // Parse the JSON generated by Llama 3.2
        const analysis = JSON.parse(result.response);

        return {
            success: true,
            analysis
        };

    } catch (error) {
        console.error("Ollama analysis failed:", error.message);
        throw error;
    }
};

module.exports = { analyzeIncident };
